# S3
# --------------------------------------------------------------------------- #
class S3Storage(StorageProvider):
    name = "s3"

    #: ``DeleteObjects`` takes at most this many keys per call.
    _DELETE_BATCH = 1000

    def __init__(self) -> None:
        import boto3  # only needed when S3 is actually in use

        options: dict[str, str] = {}
        if settings.S3_REGION:
            options["region_name"] = settings.S3_REGION
        if settings.S3_ENDPOINT_URL:
            options["endpoint_url"] = settings.S3_ENDPOINT_URL
        if settings.AWS_ACCESS_KEY_ID and settings.AWS_SECRET_ACCESS_KEY:
            options["aws_access_key_id"] = settings.AWS_ACCESS_KEY_ID
            options["aws_secret_access_key"] = settings.AWS_SECRET_ACCESS_KEY
        self.bucket = settings.S3_BUCKET
        self.client = boto3.client("s3", **options)

    async def put(self, key: str, data: bytes, content_type: str) -> None:
        await asyncio.to_thread(
            self.client.put_object,
            Bucket=self.bucket,
            Key=_check_key(key),
            Body=data,
            ContentType=content_type,
        )

    async def put_file(self, key: str, path: Path, content_type: str) -> None:
        # upload_file switches to a multipart upload for large files by itself.
        await asyncio.to_thread(
            self.client.upload_file,
            str(path),
            self.bucket,
            _check_key(key),
            ExtraArgs={"ContentType": content_type},
        )

    async def delete_many(self, keys: list[str]) -> set[str]:
        gone: set[str] = set()
        for start in range(0, len(keys), self._DELETE_BATCH):
            batch = keys[start : start + self._DELETE_BATCH]
            response = await asyncio.to_thread(
                self.client.delete_objects,
                Bucket=self.bucket,
                Delete={"Objects": [{"Key": key} for key in batch], "Quiet": True},
            )
            failed = {error["Key"] for error in response.get("Errors", [])}
            for error in response.get("Errors", []):
                logger.error("S3 refused to delete %s: %s", error.get("Key"), error.get("Message"))
            gone.update(key for key in batch if key not in failed)
        return gone

    def url_for(
        self,
        key: str,
        content_type: str,
        *,
        expires_minutes: int | None = None,
        filename: str | None = None,
    ) -> str:
        params = {"Bucket": self.bucket, "Key": key, "ResponseContentType": content_type}
        if filename:
            params["ResponseContentDisposition"] = f'attachment; filename="{filename}"'
        return self.client.generate_presigned_url(
            "get_object",
            Params=params,
            ExpiresIn=(expires_minutes or settings.SCREENSHOT_URL_EXPIRE_MINUTES) * 60,
        )


# --------------------------------------------------------------------------- #
# selection
# --------------------------------------------------------------------------- #
@lru_cache
def get_storage(name: str | None = None) -> StorageProvider:
    """The provider by name, defaulting to the configured one.

    Each stored file records which provider holds it, so files written before
    a switch from ``local`` to ``s3`` can still be shown and deleted.
    """
    chosen = (name or settings.STORAGE_PROVIDER).lower()
    if chosen == "s3":
        return S3Storage()
    return LocalStorage(settings.LOCAL_STORAGE_DIR)


def reset_storage_cache() -> None:
    """Test helper: forget providers built from earlier settings."""
    get_storage.cache_clear()


