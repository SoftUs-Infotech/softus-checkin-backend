"""Where uploaded files live: a local folder or an S3 bucket.

Picked by ``STORAGE_PROVIDER``, the way ``EMAIL_PROVIDER`` picks how mail goes
out. Callers only ever ``put``, ``delete_many`` and ask for a ``url_for`` — so
moving from the local folder to S3 is a settings change, not a code change.

Neither provider hands out a permanent public address. S3 objects are reached
through presigned URLs; local files through a link signed with ``SECRET_KEY``
and served by ``GET /files`` (see ``app/routes/files.py``). Both expire, so a
link copied out of the admin page stops working on its own.
"""

import asyncio
import hashlib
import hmac
import re
import shutil
import time
from abc import ABC, abstractmethod
from functools import lru_cache
from pathlib import Path
from urllib.parse import urlencode

from app.core.config import settings
from app.core.exceptions import PermissionDeniedError
from app.core.logging import get_logger

logger = get_logger(__name__)

#: Keys are generated by the API, never typed by a person; anything else is
#: refused before it gets near the filesystem.
_SAFE_KEY = re.compile(r"^[A-Za-z0-9_\-]+(?:/[A-Za-z0-9_\-.]+)+$")

#: Signed links are rounded up to this boundary, so the same file keeps the same
#: link for a few minutes and the browser can cache the image.
_LINK_BUCKET_SECONDS = 300


def _check_key(key: str) -> str:
    if not _SAFE_KEY.match(key) or ".." in key:
        raise ValueError(f"Refusing an unsafe storage key: {key!r}")
    return key


class StorageProvider(ABC):
    name: str = "base"

    @abstractmethod
    async def put(self, key: str, data: bytes, content_type: str) -> None:
        """Store the bytes under ``key``, or raise."""

    @abstractmethod
    async def put_file(self, key: str, path: Path, content_type: str) -> None:
        """Store a file from disk under ``key`` — for uploads too large to hold in memory."""

    @abstractmethod
    async def delete_many(self, keys: list[str]) -> set[str]:
        """Delete these keys. Returns the keys that are now gone.

        A key that was already missing counts as gone: the goal is "this file
        no longer takes space", and it doesn't.
        """

    @abstractmethod
    def url_for(
        self,
        key: str,
        content_type: str,
        *,
        expires_minutes: int | None = None,
        filename: str | None = None,
    ) -> str:
        """A short-lived link to the file; with ``filename``, a download of that name.

        Absolute (``https://…``) for S3. For local files, a path relative to the
        API prefix, which the web app joins onto its own API address.
        """


# --------------------------------------------------------------------------- #
# local folder
# --------------------------------------------------------------------------- #
def sign_local_link(key: str, expires: int) -> str:
    message = f"file:{key}:{expires}".encode()
    return hmac.new(settings.SECRET_KEY.encode(), message, hashlib.sha256).hexdigest()


def verify_local_link(key: str, expires: int, signature: str) -> None:
    """Raise unless the link was signed by this API and has not expired."""
    expected = sign_local_link(key, expires)
    if not hmac.compare_digest(expected, signature or ""):
        raise PermissionDeniedError("This link is not valid.", code="INVALID_FILE_LINK")
    if expires < time.time():
        raise PermissionDeniedError(
            "This link has expired. Reload the page to get a fresh one.",
            code="FILE_LINK_EXPIRED",
        )


class LocalStorage(StorageProvider):
    name = "local"

    def __init__(self, root: str | Path) -> None:
        self.root = Path(root).resolve()

    def path_for(self, key: str) -> Path:
        path = (self.root / _check_key(key)).resolve()
        if self.root not in path.parents:
            raise ValueError(f"Refusing a key outside the storage folder: {key!r}")
        return path

    async def put(self, key: str, data: bytes, content_type: str) -> None:
        path = self.path_for(key)

        def write() -> None:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)

        await asyncio.to_thread(write)

    async def put_file(self, key: str, path: Path, content_type: str) -> None:
        target = self.path_for(key)

        def copy() -> None:
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(path, target)

        await asyncio.to_thread(copy)

    async def delete_many(self, keys: list[str]) -> set[str]:
        def remove() -> set[str]:
            gone: set[str] = set()
            for key in keys:
                try:
                    self.path_for(key).unlink(missing_ok=True)
                    gone.add(key)
                except OSError:
                    logger.exception("Could not delete local file %s", key)
            return gone

        return await asyncio.to_thread(remove)

    async def read(self, key: str) -> bytes | None:
        path = self.path_for(key)
        if not path.is_file():
            return None
        return await asyncio.to_thread(path.read_bytes)

    def url_for(
        self,
        key: str,
        content_type: str,
        *,
        expires_minutes: int | None = None,
        filename: str | None = None,
    ) -> str:
        ttl = (expires_minutes or settings.SCREENSHOT_URL_EXPIRE_MINUTES) * 60
        expires = ((int(time.time()) + ttl) // _LINK_BUCKET_SECONDS + 1) * _LINK_BUCKET_SECONDS
        params = {
            "key": key,
            "exp": expires,
            "sig": sign_local_link(key, expires),
            "type": content_type,
        }
        if filename:
            params["name"] = filename
        return f"/files?{urlencode(params)}"


